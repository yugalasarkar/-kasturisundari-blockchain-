// अध्यायसूच्युत्पादकः
export function getAdhyayasForKhanda(khanda: Khanda): Adhyaya[] {
  if (khanda.id === 4 && khanda.totalAdhyayas === 26) {
    return BRAHMA_KHANDA_ADHYAYAS;
  }
  return Array.from({ length: khanda.totalAdhyayas }, (_, i) => {
    const chapNum = i + 1;
    let summary = `${khanda.name} — भगवन्माहात्म्य-पुण्यकथा-प्रसङ्गः`;
    if (chapNum === 1) summary = `मङ्गलाचरणम् तथा विषयप्रवेशः`;
    else if (chapNum === khanda.totalAdhyayas) summary = `${khanda.name} सम्पूर्णसमाप्तिः फलश्रुतिश्च`;

    return {
      id: chapNum,
      title: `अध्यायः ${chapNum}`,
      summary,
      verseCount: 30 + ((chapNum * 7) % 25)
    };
  });
}

